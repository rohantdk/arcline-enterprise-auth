-- Stage 3: least-privilege PostgreSQL audit migration for arcline.
-- Run with a trusted migration/admin role, never as arcline_app.
-- The SECURITY DEFINER function is owned by a dedicated NOLOGIN role,
-- not by the superuser migration account.

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_roles
        WHERE rolname = 'arcline_audit_writer'
    ) THEN
        EXECUTE 'CREATE ROLE arcline_audit_writer NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS';
    END IF;
END
$$;

-- Ensure the role remains non-login and cannot bypass database security.
ALTER ROLE arcline_audit_writer
    NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;

CREATE TABLE IF NOT EXISTS public.audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_sub VARCHAR(255),
    event_type VARCHAR(80) NOT NULL CHECK (event_type IN (
        'login_succeeded',
        'login_failed',
        'logout_succeeded',
        'authentication_denied',
        'role_authorization_denied',
        'tenant_access_denied',
        'document_access_succeeded',
        'document_access_denied'
    )),
    outcome VARCHAR(20) NOT NULL CHECK (outcome IN ('success', 'failure', 'denied')),
    organization_id VARCHAR(100),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- Runtime app can execute the audited write function but cannot access the table directly.
REVOKE ALL ON TABLE public.audit_events FROM PUBLIC, arcline_app;
GRANT USAGE ON SCHEMA public TO arcline_audit_writer;
GRANT INSERT ON TABLE public.audit_events TO arcline_audit_writer;
GRANT USAGE ON SEQUENCE public.audit_events_id_seq TO arcline_audit_writer;

CREATE OR REPLACE FUNCTION public.record_audit_event(
    p_actor_sub TEXT,
    p_event_type TEXT,
    p_outcome TEXT,
    p_organization_id TEXT,
    p_metadata JSONB
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    safe_metadata JSONB := COALESCE(p_metadata, '{}'::jsonb);
BEGIN
    IF p_event_type IS NULL OR p_event_type NOT IN (
        'login_succeeded',
        'login_failed',
        'logout_succeeded',
        'authentication_denied',
        'role_authorization_denied',
        'tenant_access_denied',
        'document_access_succeeded',
        'document_access_denied'
    ) OR p_outcome IS NULL OR p_outcome NOT IN ('success', 'failure', 'denied') THEN
        RAISE EXCEPTION 'Invalid audit event classification';
    END IF;

    IF jsonb_typeof(safe_metadata) <> 'object' THEN
        RAISE EXCEPTION 'Audit metadata must be a JSON object';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM jsonb_object_keys(safe_metadata) AS item(key)
        WHERE key NOT IN ('reason', 'required_role', 'resource', 'status_code')
    ) THEN
        RAISE EXCEPTION 'Audit metadata contains an unsupported key';
    END IF;

    INSERT INTO public.audit_events (
        actor_sub, event_type, outcome, organization_id, metadata
    ) VALUES (
        p_actor_sub, p_event_type, p_outcome, p_organization_id, safe_metadata
    );
END;
$$;

-- Function ownership is the key security boundary: use the restricted writer role.
-- Grant CREATE temporarily because PostgreSQL requires it for ownership transfer.
GRANT CREATE ON SCHEMA public TO arcline_audit_writer;
ALTER FUNCTION public.record_audit_event(TEXT, TEXT, TEXT, TEXT, JSONB)
    OWNER TO arcline_audit_writer;
REVOKE CREATE ON SCHEMA public FROM arcline_audit_writer;

REVOKE ALL ON FUNCTION public.record_audit_event(TEXT, TEXT, TEXT, TEXT, JSONB) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.record_audit_event(TEXT, TEXT, TEXT, TEXT, JSONB) TO arcline_app;

COMMIT;
